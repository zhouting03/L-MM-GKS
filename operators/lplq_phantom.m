function X = lplq_phantom(n)
% 内置分片常值 phantom，适合梯度稀疏先验，尺寸明确且无需数据文件。
[t,s]=meshgrid(linspace(-1,1,n));
X=0.08+0.50*((t/0.80).^2+(s/0.90).^2<1);
X=X-0.27*((t/0.68).^2+((s+0.02)/0.77).^2<1);
X=X+0.46*((t+0.31).^2+(s+0.20).^2<0.16^2);
X=X+0.30*(abs(t-0.27)<0.18 & abs(s+0.22)<0.13);
X=X+0.20*((t-0.05).^2+((s-0.43)/0.7).^2<0.14^2);
X=X+0.14*(abs(s-0.08)<0.025 & abs(t)<0.50);
X=X-min(X(:)); X=X/max(X(:));
end
